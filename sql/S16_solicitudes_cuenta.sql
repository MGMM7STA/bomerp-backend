CREATE TABLE BOM_PARTICIPACION.SOLICITUDES_CUENTA (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRES               VARCHAR2(80) NOT NULL,
    APELLIDOS             VARCHAR2(80) NOT NULL,
    CORREO                VARCHAR2(120) NOT NULL,
    CODIGO_UNIVERSITARIO  VARCHAR2(20) NOT NULL,
    DNI                   VARCHAR2(8) NOT NULL,
    ESCUELA               VARCHAR2(120) NOT NULL,
    CICLO                 NUMBER(2) NOT NULL,
    CELULAR               VARCHAR2(15) NOT NULL,
    ARCHIVO_CARNE         VARCHAR2(120),
    ESTADO                VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    MOTIVO_RECHAZO        VARCHAR2(300),
    FECHA_SOLICITUD       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_REVISION        TIMESTAMP,
    REVISADO_POR          VARCHAR2(150),
    USUARIO_CREADO        VARCHAR2(80),
    CONSTRAINT CK_SOLICITUD_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    CONSTRAINT CK_SOLICITUD_CICLO CHECK (CICLO BETWEEN 1 AND 14)
);

CREATE INDEX IX_SOLICITUD_ESTADO ON BOM_PARTICIPACION.SOLICITUDES_CUENTA (ESTADO, FECHA_SOLICITUD);

GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_PARTICIPACION.SOLICITUDES_CUENTA TO BOMERP_APP;

