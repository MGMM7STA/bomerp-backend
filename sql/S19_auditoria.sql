CREATE TABLE BOM_AUDITORIA.EVENTOS (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FECHA       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    USUARIO     VARCHAR2(80)  NOT NULL,
    NOMBRE      VARCHAR2(150),
    ACCION      VARCHAR2(40)  NOT NULL,
    ENTIDAD     VARCHAR2(40)  NOT NULL,
    ENTIDAD_ID  VARCHAR2(60),
    DETALLE     VARCHAR2(500),
    SEDE        VARCHAR2(10),
    TRACE_ID    VARCHAR2(64)
);

CREATE INDEX IX_EVENTOS_FECHA ON BOM_AUDITORIA.EVENTOS (FECHA);
CREATE INDEX IX_EVENTOS_ACCION ON BOM_AUDITORIA.EVENTOS (ACCION, FECHA);

