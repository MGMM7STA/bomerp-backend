SET FEEDBACK ON

CREATE TABLE BOM_PARTICIPACION.SEDES_USUARIO (
    USUARIO  VARCHAR2(80) PRIMARY KEY,
    SEDE     VARCHAR2(10) NOT NULL,
    CONSTRAINT CK_SEDE_USUARIO CHECK (SEDE IN ('LIMA', 'JULIACA', 'TARAPOTO'))
);

GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_PARTICIPACION.SEDES_USUARIO TO BOMERP_APP;

ALTER TABLE BOM_PARTICIPACION.ESTUDIANTES ADD (
    SEDE  VARCHAR2(10) CONSTRAINT CK_ESTUDIANTE_SEDE CHECK (SEDE IN ('LIMA', 'JULIACA', 'TARAPOTO'))
);

ALTER TABLE BOM_PARTICIPACION.REGISTROS ADD (
    SEDE  VARCHAR2(10) CONSTRAINT CK_REGISTRO_SEDE CHECK (SEDE IN ('LIMA', 'JULIACA', 'TARAPOTO'))
);

CREATE INDEX IX_REGISTRO_SEDE ON BOM_PARTICIPACION.REGISTROS (SEDE, ESTADO, FECHA);

CREATE TABLE BOM_CAMPANIAS.CAMPANIA_SEDES (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CAMPANIA  NUMBER NOT NULL,
    SEDE         VARCHAR2(10) NOT NULL,
    CONSTRAINT UK_CAMPANIA_SEDE UNIQUE (ID_CAMPANIA, SEDE),
    CONSTRAINT CK_CAMPANIA_SEDE CHECK (SEDE IN ('LIMA', 'JULIACA', 'TARAPOTO')),
    CONSTRAINT FK_CS_CAMPANIA FOREIGN KEY (ID_CAMPANIA)
        REFERENCES BOM_CAMPANIAS.CAMPANIAS(ID) ON DELETE CASCADE
);

GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_CAMPANIAS.CAMPANIA_SEDES TO BOMERP_APP;

ALTER TABLE BOM_PARTICIPACION.SOLICITUDES_CUENTA ADD (
    ODOO_LEAD_ID  NUMBER,
    SEDE          VARCHAR2(10)
);

ALTER TABLE BOM_PARTICIPACION.SOLICITUDES_CUENTA MODIFY (
    CODIGO_UNIVERSITARIO  NULL,
    DNI                   NULL,
    ESCUELA               NULL,
    CICLO                 NULL,
    CELULAR               NULL
);

CREATE UNIQUE INDEX UX_SOLICITUD_LEAD ON BOM_PARTICIPACION.SOLICITUDES_CUENTA (ODOO_LEAD_ID);

ALTER TABLE BOM_PREMIOS.ACTAS_PREMIACION ADD (
    SEDE  VARCHAR2(10) CONSTRAINT CK_ACTA_SEDE CHECK (SEDE IN ('LIMA', 'JULIACA', 'TARAPOTO'))
);

UPDATE BOM_PREMIOS.ACTAS_PREMIACION SET SEDE = 'JULIACA' WHERE SEDE IS NULL;

ALTER TABLE BOM_PREMIOS.ACTAS_PREMIACION MODIFY (SEDE NOT NULL);

ALTER TABLE BOM_PREMIOS.ACTAS_PREMIACION DROP CONSTRAINT UK_ACTA_CAMPANIA_PERIODO;

ALTER TABLE BOM_PREMIOS.ACTAS_PREMIACION ADD CONSTRAINT UK_ACTA_CAMPANIA_PERIODO
    UNIQUE (CAMPANIA_ID, SEDE, FECHA_INICIO_PERIODO, FECHA_FIN_PERIODO);

