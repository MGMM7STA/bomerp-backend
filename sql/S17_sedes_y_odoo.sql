  SELECT 'coordinador1', 'JULIACA' FROM DUAL
  WHERE NOT EXISTS (SELECT 1 FROM BOM_PARTICIPACION.SEDES_USUARIO WHERE USUARIO = 'coordinador1');

UPDATE BOM_PARTICIPACION.ESTUDIANTES SET SEDE = 'JULIACA' WHERE SEDE IS NULL;

UPDATE BOM_PARTICIPACION.REGISTROS SET SEDE = 'JULIACA' WHERE SEDE IS NULL;

