CREATE OR REPLACE FUNCTION BOM_PARTICIPACION.OBTENER_PUNTAJE_ESTUDIANTE (
    p_estudiante IN NUMBER,
    p_campania   IN NUMBER
) RETURN NUMBER IS
    v_existe NUMBER;
    v_puntos NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM BOM_PARTICIPACION.ESTUDIANTES
     WHERE ID = p_estudiante;

    IF v_existe = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'El estudiante ' || p_estudiante || ' no existe');
    END IF;

    SELECT NVL(SUM(d.SUBTOTAL), 0) INTO v_puntos
      FROM BOM_PARTICIPACION.REGISTROS r
      JOIN BOM_PARTICIPACION.DETALLE_EVIDENCIAS d ON d.ID_REGISTRO = r.ID
     WHERE r.ID_ESTUDIANTE = p_estudiante
       AND r.ID_CAMPANIA = p_campania
       AND d.ESTADO = 'VALIDADO';

    RETURN v_puntos;
END;
/

CREATE OR REPLACE FUNCTION BOM_PARTICIPACION.HABITO_MAS_REGISTRADO (
    p_campania IN NUMBER,
    p_sede     IN VARCHAR2 DEFAULT NULL
) RETURN VARCHAR2 IS
    v_nombre BOM_PARTICIPACION.DETALLE_EVIDENCIAS.NOMBRE_HABITO%TYPE;
BEGIN
    SELECT NOMBRE_HABITO INTO v_nombre
      FROM (SELECT d.NOMBRE_HABITO, SUM(d.VECES) AS TOTAL
              FROM BOM_PARTICIPACION.REGISTROS r
              JOIN BOM_PARTICIPACION.DETALLE_EVIDENCIAS d ON d.ID_REGISTRO = r.ID
             WHERE r.ID_CAMPANIA = p_campania
               AND (p_sede IS NULL OR r.SEDE = p_sede)
               AND d.ESTADO <> 'ANULADO'
             GROUP BY d.NOMBRE_HABITO
             ORDER BY TOTAL DESC, d.NOMBRE_HABITO)
     WHERE ROWNUM = 1;

    RETURN v_nombre;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'Sin registros';
END;
/

CREATE OR REPLACE TRIGGER BOM_AUDITORIA.TRG_EVENTOS_INMUTABLE
BEFORE UPDATE OR DELETE ON BOM_AUDITORIA.EVENTOS
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20010,
        'La auditoria no se modifica ni se borra: evento ' || :OLD.ID || ' de ' || :OLD.USUARIO);
END;
/

