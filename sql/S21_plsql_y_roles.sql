GRANT SELECT ON BOM_PARTICIPACION.REGISTROS TO ROL_REPORTES;
GRANT SELECT ON BOM_PARTICIPACION.DETALLE_EVIDENCIAS TO ROL_REPORTES;
GRANT SELECT ON BOM_PARTICIPACION.ESTUDIANTES TO ROL_REPORTES;
GRANT SELECT ON BOM_AUDITORIA.EVENTOS TO ROL_REPORTES;
GRANT EXECUTE ON BOM_PARTICIPACION.OBTENER_PUNTAJE_ESTUDIANTE TO ROL_REPORTES;
GRANT EXECUTE ON BOM_PARTICIPACION.HABITO_MAS_REGISTRADO TO ROL_REPORTES;

COLUMN OWNER FORMAT A18
COLUMN OBJECT_NAME FORMAT A28
COLUMN OBJECT_TYPE FORMAT A10
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM DBA_OBJECTS
 WHERE OBJECT_NAME IN ('OBTENER_PUNTAJE_ESTUDIANTE', 'HABITO_MAS_REGISTRADO', 'TRG_EVENTOS_INMUTABLE')
 ORDER BY OWNER, OBJECT_NAME;

COLUMN USUARIO FORMAT A14
COLUMN HABITO FORMAT A30
SELECT e.ID, e.USUARIO,
       BOM_PARTICIPACION.OBTENER_PUNTAJE_ESTUDIANTE(e.ID, c.ID) AS PUNTOS_VALIDADOS,
       BOM_PARTICIPACION.HABITO_MAS_REGISTRADO(c.ID) AS HABITO
  FROM BOM_PARTICIPACION.ESTUDIANTES e
 CROSS JOIN (SELECT MIN(ID) AS ID FROM BOM_CAMPANIAS.CAMPANIAS WHERE ESTADO = 'ACTIVA') c
 ORDER BY e.ID;

