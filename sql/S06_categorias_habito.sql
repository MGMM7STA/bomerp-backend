    (SELECT ID FROM BOM_CAMPANIAS.CATEGORIAS_HABITO WHERE NOMBRE = 'Actividad fisica')
WHERE NOMBRE = 'Caminata de 30 minutos';

UPDATE BOM_CAMPANIAS.HABITOS SET ID_CATEGORIA =
    (SELECT ID FROM BOM_CAMPANIAS.CATEGORIAS_HABITO WHERE NOMBRE = 'Alimentacion')
WHERE NOMBRE = 'Consumo de frutas';

UPDATE BOM_CAMPANIAS.HABITOS SET ID_CATEGORIA =
    (SELECT ID FROM BOM_CAMPANIAS.CATEGORIAS_HABITO WHERE NOMBRE = 'Descanso')
WHERE NOMBRE = 'Dormir 7 horas';

UPDATE BOM_CAMPANIAS.HABITOS SET ID_CATEGORIA =
    (SELECT MIN(ID) FROM BOM_CAMPANIAS.CATEGORIAS_HABITO)
WHERE ID_CATEGORIA IS NULL;

COMMIT;

ALTER TABLE BOM_CAMPANIAS.HABITOS MODIFY (ID_CATEGORIA NOT NULL);

ALTER TABLE BOM_CAMPANIAS.HABITOS
    ADD CONSTRAINT FK_HABITO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
    REFERENCES BOM_CAMPANIAS.CATEGORIAS_HABITO (ID);

GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_CAMPANIAS.CATEGORIAS_HABITO TO BOMERP_APP;

SELECT h.ID, h.NOMBRE, c.NOMBRE AS CATEGORIA
FROM   BOM_CAMPANIAS.HABITOS h
JOIN   BOM_CAMPANIAS.CATEGORIAS_HABITO c ON c.ID = h.ID_CATEGORIA
