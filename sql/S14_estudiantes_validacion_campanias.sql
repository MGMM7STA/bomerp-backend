-- ---------- 3. Habitos de cada campania ----------
CREATE TABLE BOM_CAMPANIAS.CAMPANIA_HABITOS (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CAMPANIA  NUMBER NOT NULL,
    ID_HABITO    NUMBER NOT NULL,
    CONSTRAINT UK_CAMPANIA_HABITO UNIQUE (ID_CAMPANIA, ID_HABITO),
    CONSTRAINT FK_CH_CAMPANIA FOREIGN KEY (ID_CAMPANIA)
        REFERENCES BOM_CAMPANIAS.CAMPANIAS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_CH_HABITO FOREIGN KEY (ID_HABITO)
        REFERENCES BOM_CAMPANIAS.HABITOS(ID) ON DELETE CASCADE
);

GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_CAMPANIAS.CAMPANIA_HABITOS TO BOMERP_APP;

INSERT INTO BOM_CAMPANIAS.CAMPANIA_HABITOS (ID_CAMPANIA, ID_HABITO)
  SELECT c.ID, h.ID
    FROM BOM_CAMPANIAS.CAMPANIAS c
    CROSS JOIN BOM_CAMPANIAS.HABITOS h
   WHERE c.ESTADO = 'ACTIVA' AND h.ACTIVO = 1;
COMMIT;

SELECT 'ESTUDIANTES' AS TABLA, COUNT(*) AS FILAS FROM BOM_PARTICIPACION.ESTUDIANTES
UNION ALL
SELECT 'CAMPANIA_HABITOS', COUNT(*) FROM BOM_CAMPANIAS.CAMPANIA_HABITOS;
