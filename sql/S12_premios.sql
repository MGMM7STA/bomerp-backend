CREATE USER BOM_PREMIOS IDENTIFIED BY "123456" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW TO BOM_PREMIOS;

CREATE TABLE BOM_PREMIOS.CATEGORIAS_PREMIO (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE       VARCHAR2(80) NOT NULL,
    DESCRIPCION  VARCHAR2(200),
    CONSTRAINT UK_CATEGORIA_PREMIO_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE BOM_PREMIOS.PREMIOS (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE        VARCHAR2(100) NOT NULL,
    DESCRIPCION   VARCHAR2(200),
    STOCK         NUMBER(10) NOT NULL,
    ACTIVO        NUMBER(1) DEFAULT 1 NOT NULL,
    CATEGORIA_ID  NUMBER NOT NULL,
    CONSTRAINT UK_PREMIO_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT FK_PREMIO_CATEGORIA FOREIGN KEY (CATEGORIA_ID)
        REFERENCES BOM_PREMIOS.CATEGORIAS_PREMIO(ID),
    CONSTRAINT CK_PREMIO_STOCK CHECK (STOCK >= 0)
);

CREATE TABLE BOM_PREMIOS.ACTAS_PREMIACION (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CAMPANIA_ID               NUMBER NOT NULL,
    FECHA_INICIO_PERIODO      DATE NOT NULL,
    FECHA_FIN_PERIODO         DATE NOT NULL,
    FECHA_EMISION             TIMESTAMP NOT NULL,
    ESTADO                    VARCHAR2(20) NOT NULL,
    TOTAL_GANADORES           NUMBER(10) NOT NULL,
    TOTAL_PREMIOS_ENTREGADOS  NUMBER(10) NOT NULL,
    CONSTRAINT UK_ACTA_CAMPANIA_PERIODO UNIQUE
        (CAMPANIA_ID, FECHA_INICIO_PERIODO, FECHA_FIN_PERIODO),
    CONSTRAINT CK_ACTA_ESTADO CHECK (ESTADO IN ('EMITIDA', 'ANULADA')),
    CONSTRAINT CK_ACTA_PERIODO CHECK (FECHA_FIN_PERIODO >= FECHA_INICIO_PERIODO)
);

CREATE TABLE BOM_PREMIOS.DETALLES_PREMIACION (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTA_ID            NUMBER NOT NULL,
    ESTUDIANTE_ID      NUMBER NOT NULL,
    POSICION           NUMBER(10) NOT NULL,
    PREMIO_ID          NUMBER NOT NULL,
    CANTIDAD           NUMBER(10) NOT NULL,
    PUNTAJE_ALCANZADO  NUMBER(10) NOT NULL,
    CONSTRAINT FK_DETALLE_ACTA FOREIGN KEY (ACTA_ID)
        REFERENCES BOM_PREMIOS.ACTAS_PREMIACION(ID),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_POSICION CHECK (POSICION > 0)
);

