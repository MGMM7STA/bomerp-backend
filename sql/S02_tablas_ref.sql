ALTER USER BOM_CATALOGO QUOTA UNLIMITED ON USERS;
ALTER SESSION SET CURRENT_SCHEMA = BOM_CATALOGO;

CREATE TABLE CATEGORIA (
  ID_CATEGORIA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE       VARCHAR2(80)  NOT NULL,
  DESCRIPCION  VARCHAR2(200),
  CONSTRAINT PK_CATEGORIA        PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UK_CATEGORIA_NOMBRE UNIQUE      (NOMBRE)
);

CREATE TABLE PRODUCTO (
  ID_PRODUCTO  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE       VARCHAR2(120) NOT NULL,
  PRECIO       NUMBER(10,2)  NOT NULL,
  STOCK        NUMBER(10)    DEFAULT 0 NOT NULL,
  ID_CATEGORIA NUMBER        DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PRODUCTO           PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA),
  CONSTRAINT CK_PRODUCTO_PRECIO    CHECK (PRECIO >= 0),
  CONSTRAINT CK_PRODUCTO_STOCK     CHECK (STOCK  >= 0)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_CATALOGO.CATEGORIA TO BOMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON BOM_CATALOGO.PRODUCTO  TO BOMERP_APP;
