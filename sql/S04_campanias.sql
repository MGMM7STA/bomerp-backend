CREATE TABLE BOM_CAMPANIAS.CAMPANIAS (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE              VARCHAR2(120) NOT NULL,
    FECHA_INICIO        DATE NOT NULL,
    FECHA_FIN           DATE NOT NULL,
    MAX_EVIDENCIAS_DIA  NUMBER(3) NOT NULL,
    ESTADO              VARCHAR2(20) NOT NULL,
    CONSTRAINT CK_CAMPANIA_MAX CHECK (MAX_EVIDENCIAS_DIA > 0)
);

CREATE TABLE BOM_CAMPANIAS.HABITOS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE         VARCHAR2(120) NOT NULL,
    DESCRIPCION    VARCHAR2(255),
    PUNTAJE_BASE   NUMBER(10,2) NOT NULL,
    ACTIVO         NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_HABITO_PUNTAJE CHECK (PUNTAJE_BASE > 0)
);

CREATE TABLE BOM_CAMPANIAS.CUPOS_DIARIOS (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CAMPANIA        NUMBER NOT NULL,
    ID_ESTUDIANTE      NUMBER NOT NULL,
    FECHA              DATE NOT NULL,
    EVIDENCIAS_USADAS  NUMBER(5) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_CUPO_CAMPANIA FOREIGN KEY (ID_CAMPANIA)
        REFERENCES BOM_CAMPANIAS.CAMPANIAS(ID),
    CONSTRAINT UK_CUPO_DIA UNIQUE (ID_CAMPANIA, ID_ESTUDIANTE, FECHA),
    CONSTRAINT CK_CUPO_USADAS CHECK (EVIDENCIAS_USADAS >= 0)
);

CREATE TABLE BOM_PARTICIPACION.REGISTROS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ESTUDIANTE     NUMBER NOT NULL,
    ID_CAMPANIA       NUMBER NOT NULL,
    FECHA             TIMESTAMP NOT NULL,
    ESTADO            VARCHAR2(20) NOT NULL,
    TOTAL_EVIDENCIAS  NUMBER(5) NOT NULL,
    PUNTAJE_TOTAL     NUMBER(12,2) NOT NULL,
    CONSTRAINT CK_REGISTRO_PUNTAJE CHECK (PUNTAJE_TOTAL >= 0),
    CONSTRAINT CK_REGISTRO_TOTALEV CHECK (TOTAL_EVIDENCIAS > 0)
);

CREATE TABLE BOM_PARTICIPACION.DETALLE_EVIDENCIAS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_REGISTRO       NUMBER NOT NULL,
    ID_HABITO         NUMBER NOT NULL,
    NOMBRE_HABITO     VARCHAR2(120) NOT NULL,
    DESCRIPCION       VARCHAR2(255),
    URL_IMAGEN        VARCHAR2(255),
    PUNTAJE_UNITARIO  NUMBER(10,2) NOT NULL,
    VECES             NUMBER(5) NOT NULL,
    SUBTOTAL          NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_EVIDENCIA_REGISTRO FOREIGN KEY (ID_REGISTRO)
        REFERENCES BOM_PARTICIPACION.REGISTROS(ID),
    CONSTRAINT CK_EVID_VECES CHECK (VECES > 0),
    CONSTRAINT CK_EVID_SUBTOTAL CHECK (SUBTOTAL >= 0)
);

