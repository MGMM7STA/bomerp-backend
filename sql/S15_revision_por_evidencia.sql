SET DEFINE OFF
SET FEEDBACK ON

ALTER TABLE BOM_PARTICIPACION.DETALLE_EVIDENCIAS ADD (
    ESTADO          VARCHAR2(20) DEFAULT 'ENVIADO' NOT NULL,
    MOTIVO_RECHAZO  VARCHAR2(300),
    ARCHIVO_IMAGEN  VARCHAR2(120)
);

ALTER TABLE BOM_PARTICIPACION.DETALLE_EVIDENCIAS ADD CONSTRAINT CK_DETALLE_ESTADO
  CHECK (ESTADO IN ('BORRADOR', 'ENVIADO', 'VALIDADO', 'RECHAZADO', 'ANULADO'));

UPDATE BOM_PARTICIPACION.DETALLE_EVIDENCIAS d
   SET (d.ESTADO, d.MOTIVO_RECHAZO) = (
       SELECT r.ESTADO, CASE WHEN r.ESTADO = 'RECHAZADO' THEN r.MOTIVO_RECHAZO END
         FROM BOM_PARTICIPACION.REGISTROS r
        WHERE r.ID = d.ID_REGISTRO);

UPDATE BOM_PARTICIPACION.DETALLE_EVIDENCIAS d
   SET d.NOMBRE_HABITO = (SELECT h.NOMBRE FROM BOM_CAMPANIAS.HABITOS h WHERE h.ID = d.ID_HABITO)
 WHERE d.NOMBRE_HABITO = 'Habito sembrado'
   AND EXISTS (SELECT 1 FROM BOM_CAMPANIAS.HABITOS h WHERE h.ID = d.ID_HABITO);

COMMIT;

SELECT ESTADO, COUNT(*) AS EVIDENCIAS
  FROM BOM_PARTICIPACION.DETALLE_EVIDENCIAS
 GROUP BY ESTADO;
