SET DEFINE OFF
SET FEEDBACK ON
SET LONG 60

ALTER TABLE BOM_PARTICIPACION.REGISTROS MODIFY
    PARTITION BY RANGE (FECHA) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
    (PARTITION P_INICIAL VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00'))
    ONLINE;

EXEC DBMS_STATS.GATHER_TABLE_STATS('BOM_PARTICIPACION', 'REGISTROS');

COLUMN PARTITION_NAME FORMAT A16
COLUMN HIGH_VALUE FORMAT A45
SELECT PARTITION_NAME, HIGH_VALUE, NUM_ROWS
  FROM DBA_TAB_PARTITIONS
 WHERE TABLE_OWNER = 'BOM_PARTICIPACION' AND TABLE_NAME = 'REGISTROS'
 ORDER BY PARTITION_POSITION;

EXPLAIN PLAN FOR
SELECT SUM(PUNTAJE_TOTAL)
  FROM BOM_PARTICIPACION.REGISTROS
 WHERE FECHA >= TIMESTAMP '2026-11-01 00:00:00'
   AND FECHA <  TIMESTAMP '2026-12-01 00:00:00';

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY(NULL, NULL, 'BASIC +PARTITION'));
